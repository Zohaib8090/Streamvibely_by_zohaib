#!/usr/bin/env python3
"""Generate Kotlin theme tokens from design-system/tokens/tokens.json.
Run from the repo root: python3 design-system/generate_tokens.py
Do not edit the generated Tokens.kt by hand."""
import json, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
t = json.loads((root / "design-system/tokens/tokens.json").read_text())
out = root / "composeApp/src/commonMain/kotlin/app/streamvibely/theme/Tokens.kt"

def c(hexv): return f"Color(0xFF{hexv.lstrip('#').upper()})"
lines = ["// GENERATED by design-system/generate_tokens.py from tokens.json. Do not edit.",
         "package app.streamvibely.theme", "", "import androidx.compose.ui.graphics.Color", "",
         "/** Corner radii. Multiply by the theme's corner scale: `Tokens.radiusCard.dp.scaled()`. */",
         "object Tokens {"]
for k, v in t["shape"]["radii"].items():
    lines.append(f"    const val radius{k[0].upper()+k[1:]} = {v}")
lines.append("}")
lines.append("")
lines.append("/** The original lime-green colors from the Figma mockup. Kept for reference; the UI must not use them. */")
lines.append("object LegacyLime {")
for k, v in t["color"]["dark"].items():
    lines.append(f"    val {k} = {c(v['value'])}")
lines.append("")
for k, v in t["color"]["categoryTiles"].items():
    lines.append(f"    val tile{k[0].upper()+k[1:]} = {c(v)}")
lines.append("}")
out.write_text("\n".join(lines) + "\n")
print("wrote", out)
