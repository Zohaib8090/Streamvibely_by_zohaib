def fname(sym, filled): return f"{sym}{'_fill' if filled else ''}.svg"

def fetch():
    svg_dir.mkdir(parents=True, exist_ok=True)
    missing=[]
    for k,(sym,fill) in ICONS.items():
        dst = svg_dir / fname(sym, fill)
        if dst.exists() and dst.stat().st_size>0: continue
        url = BASE.format(n=sym, f="_fill1" if fill else "")
        r = subprocess.run(["curl","-sf","--max-time","25","-o",str(dst),url])
        if r.returncode!=0 or not dst.exists() or dst.stat().st_size==0:
            missing.append(k); dst.unlink(missing_ok=True)
    print("missing:", missing)

def gen():
    lines=["// GENERATED by design-system/generate_icons.py from design-system/icons/*.svg. Do not edit.",
           "// Icon artwork: Material Symbols Rounded, Apache License 2.0, Google.",
           "package app.streamvibely.ui.common","",
           "import androidx.compose.ui.graphics.Color","import androidx.compose.ui.graphics.SolidColor",
           "import androidx.compose.ui.graphics.vector.ImageVector","import androidx.compose.ui.graphics.vector.PathParser",
           "import androidx.compose.ui.graphics.vector.group","import androidx.compose.ui.unit.dp","",
           "/** Every icon in the app. Draw them with [AppIcon]. */","object AppIcons {"]
    n=0
    for k,(sym,fill) in ICONS.items():
        f = svg_dir / fname(sym, fill)
        if not f.exists(): continue
        paths = re.findall(r'\sd="([^"]+)"', f.read_text())
        if not paths: continue
        args = ", ".join('"%s"' % p.replace("\\","\\\\").replace("$","\\$") for p in paths)
        lines.append(f'    val {k}: ImageVector by lazy {{ symbol("{k}", {args}) }}')
        n+=1
    lines += ["}","",
      "/** Material Symbols use a 960x960 viewport whose origin is at the bottom left (y from -960 to 0). */",
      "private fun symbol(name: String, vararg paths: String): ImageVector =",
      "    ImageVector.Builder(name, 24.dp, 24.dp, 960f, 960f).apply {",
      "        group(translationY = 960f) {",
      "            paths.forEach { d -> addPath(PathParser().parsePathString(d).toNodes(), fill = SolidColor(Color.Black)) }",
      "        }",
      "    }.build()",""]
    out.write_text("\n".join(lines))
    print("wrote", out, n, "icons")

{"fetch":fetch,"gen":gen}[sys.argv[1]]()
